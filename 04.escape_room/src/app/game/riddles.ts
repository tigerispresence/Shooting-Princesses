function shuffle<T>(list: readonly T[]): T[] {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * 한 방에 낼 문제를 뽑는다.
 *
 * 같은 종류가 연달아 나오면 "또 계산 문제야?" 소리가 나오므로, 종류가 겹치지
 * 않는 것부터 채우고 모자랄 때만 겹치게 둔다. 통이 비는 일이 없도록 난이도가
 * 모자라면 한 단계 아래 통까지 끌어다 쓴다.
 */
export function pickRiddles(level: QuizLevel, count: number): Riddle[] {
  const ladder: QuizLevel[] =
    level === "hard" ? ["hard", "mid", "easy"] : level === "mid" ? ["mid", "easy", "hard"] : ["easy", "mid", "hard"];

  const pool: Riddle[] = [];
  for (const lv of ladder) {
    pool.push(...shuffle(RIDDLES.filter((r) => r.level === lv)));
    if (pool.length >= count * 3) break;
  }

  const out: Riddle[] = [];
  const usedTags = new Set<QuizTag>();
  for (const r of pool) {
    if (out.length >= count) break;
    if (usedTags.has(r.tag)) continue;
    usedTags.add(r.tag);
    out.push(r);
  }
  for (const r of pool) {
    if (out.length >= count) break;
    if (!out.includes(r)) out.push(r);
  }
  return out;
}
