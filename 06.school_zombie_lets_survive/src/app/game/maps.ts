const SOLID = "#TLP";

function roomAt(rooms: RoomDef[], x: number, y: number): number {
  for (let i = 0; i < rooms.length; i++) {
    const r = rooms[i];
    if (x >= r.x && x < r.x + r.w && y >= r.y && y < r.y + r.h) return i;
  }
  return -1;
}

/**
 * ASCII 한 장을 타일 정보로 바꾼다.
 *
 * 사람·물건 글자(`S`, `z`, 재료 …) 밑에 깔린 바닥은 이웃을 보고 정한다 —
 * 복도 칸(`.`)에 둘러싸여 있으면 복도, 아니면 방 바닥.
 */
export function parseMap(stage: StageDef): MapData {
  const raw = stage.map;
  const h = raw.length;
  const w = raw[0].length;
  const tiles: TileInfo[] = new Array(w * h);

  const charAt = (x: number, y: number): string =>
    x < 0 || y < 0 || x >= w || y >= h ? "#" : raw[y][x];

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = charAt(x, y);
      let corridor = ch === ".";
      if (!",.#TLP".includes(ch)) {
        // 물건이 놓인 칸 — 주변을 보고 복도인지 방인지 정한다
        let dot = 0;
        let comma = 0;
        for (const [dx, dy] of [
          [1, 0],
          [-1, 0],
          [0, 1],
          [0, -1],
        ]) {
          const n = charAt(x + dx, y + dy);
          if (n === ".") dot++;
          else if (n === ",") comma++;
        }
        corridor = dot > comma;
      }
      tiles[y * w + x] = {
        solid: SOLID.includes(ch),
        blocksSight: ch === "#" || ch === "T" || ch === "P",
        locker: ch === "L",
        door: ch === "D",
        corridor,
        exit: ch === "E",
        pillar: ch === "P",
        broadcast: ch === "R",
        beaker: ch === "Y",
        chalkPile: ch === "C" && stage.id === 1,
        room: roomAt(stage.rooms, x, y),
      };
    }
  }
  return { w, h, tiles, rooms: stage.rooms, raw };
}

export function tileAt(map: MapData, tx: number, ty: number): TileInfo | null {
  if (tx < 0 || ty < 0 || tx >= map.w || ty >= map.h) return null;
  return map.tiles[ty * map.w + tx];
}
